#!/usr/bin/env python3
"""gen_layer0_ref.py — emit qwen_engine_layer0_ref.h (trusted host reference).

Computes layer-0 forward for P0 prompt-1 first token (105538) using the
weights_kal/ files (K-aligned INT4 G32) and the SAME two-pass INT4 semantics
the engine implements (emu_group_int4.matmul_group_i4).  Emits reference
vectors for the engine probe to compare against:

  ref_attn[896]      : attention output (before o_proj)
  ref_after_wo[896]  : x + o_proj(attn)   (after attention block residual)
  ref_after_ffn[896] : x + down(silu(up*gate)) (final layer-0 output)

All fp32, rounded to 8 decimals.  This is the cross-check for the on-board
qwen_engine_layer0 probe (TIU path vs host reference).
"""
import os
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import emu_group_int4 as E4
from emu_perrow import D, KVH, DKV, L, F, G, HD, H, GROUPS, ROPE_THETA, EPS
from qwen_emu import precompute_rope, rope, rms_norm, silu
import verify_kal_roundtrip as R

D = 896
KVH = 2
DKV = KVH * 64
F = 4864
G = 32

wdir = os.path.join(HERE, "weights_kal")
TOKEN = 105538  # P0 prompt 1 "中国的首都是" first token


def main():
    layers = R.load_layers(wdir)
    embed = np.fromfile(os.path.join(wdir, "embed_i8.bin"), dtype=np.int8).reshape(-1, D)
    esc = np.fromfile(os.path.join(wdir, "embed_scales.f32"), dtype=np.float32)

    # layer 0
    rms_attn, mats, rms_ffn, bias, gsc = layers[0]
    bq, bk, bv = bias[:D], bias[D:D + DKV], bias[D + DKV:]

    # x = embed[t] * esc[t]  (single token)
    x = (embed[TOKEN].astype(np.float32) * esc[TOKEN]).astype(np.float32)

    h = rms_norm(x[None, :], rms_attn)[0]
    x_i8, sc_row = E4.C8.quant_per_row(h[None, :])
    x_i8 = x_i8[0]
    sc_row = sc_row[0]

    q = E4.matmul_group_i4(x_i8[None, :], mats["Wq"], gsc["Wq"], sc_row[None])[0] + bq
    k = E4.matmul_group_i4(x_i8[None, :], mats["Wk"], gsc["Wk"], sc_row[None])[0] + bk
    v = E4.matmul_group_i4(x_i8[None, :], mats["Wv"], gsc["Wv"], sc_row[None])[0] + bv

    cos, sin = precompute_rope(8, HD, ROPE_THETA)
    q = q.reshape(H, HD)
    k = k.reshape(KVH, HD)
    v = v.reshape(KVH, HD)
    for hh in range(H):
        q[hh] = rope(q[hh], 0, cos, sin, HD)
    for hh in range(KVH):
        k[hh] = rope(k[hh], 0, cos, sin, HD)

    # attention (seq=1 -> softmax over single key = v); GQA head group map
    attn = np.zeros((H, HD), np.float32)
    for hh in range(H):
        kvh = hh // GROUPS
        attn[hh] = v[kvh]
    attn = attn.reshape(D).copy()       # pr=1.0
    ref_attn = attn.copy()

    a_i8, sc_a = E4.C8.quant_per_row(attn[None, :])
    a_i8 = a_i8[0]
    sc_a = sc_a[0]
    wo = E4.matmul_group_i4(a_i8[None, :], mats["Wo"], gsc["Wo"], sc_a[None])[0]
    x_after_wo = x + wo
    ref_after_wo = x_after_wo.copy()

    h2 = rms_norm(x_after_wo[None, :], rms_ffn)[0]
    x2_i8, sc2 = E4.C8.quant_per_row(h2[None, :])
    x2_i8 = x2_i8[0]
    sc2 = sc2[0]
    up = E4.matmul_group_i4(x2_i8[None, :], mats["up"], gsc["up"], sc2[None])[0]
    gate = E4.matmul_group_i4(x2_i8[None, :], mats["gate"], gsc["gate"], sc2[None])[0]
    mid = up * silu(gate)
    out = np.zeros(D, np.float32)
    for kc in range(0, F, 1024):
        kcn = min(1024, F - kc)
        m_i8, sc_m = E4.C8.quant_per_row(mid[kc:kc + kcn][None, :])
        m_i8 = m_i8[0]
        sc_m = sc_m[0]
        wc = mats["down"][kc:kc + kcn, :]
        gsw = gsc["down"][kc // G:(kc + kcn) // G, :]
        out += E4.matmul_group_i4(m_i8[None, :], wc, gsw, sc_m[None])[0]
    x_after_ffn = x_after_wo + out
    ref_after_ffn = x_after_ffn.copy()

    def wv(name, arr):
        return "".join(f"{float(v):.8e}," for v in arr)

    with open(os.path.join(HERE, "qwen_engine_layer0_ref.h"), "w") as f:
        f.write("/* qwen_engine_layer0_ref.h — generated by gen_layer0_ref.py (DO NOT EDIT). */\n")
        f.write(f"/* token={TOKEN} P0 prompt1 first token, weights_kal layer0 */\n")
        f.write("#define REF_D 896\n")
        f.write("static const float ref_attn[896] = {" + wv("a", ref_attn) + "};\n")
        f.write("static const float ref_after_wo[896] = {" + wv("w", ref_after_wo) + "};\n")
        f.write("static const float ref_after_ffn[896] = {" + wv("f", ref_after_ffn) + "};\n")
    print(f"wrote qwen_engine_layer0_ref.h")
    print(f"  attn[0..3]={ref_attn[0]:.6f} {ref_attn[1]:.6f} {ref_attn[2]:.6f} {ref_attn[3]:.6f}")
    print(f"  after_wo[0..3]={ref_after_wo[0]:.6f} {ref_after_wo[1]:.6f} {ref_after_wo[2]:.6f} {ref_after_wo[3]:.6f}")
    print(f"  after_ffn[0..3]={ref_after_ffn[0]:.6f} {ref_after_ffn[1]:.6f} {ref_after_ffn[2]:.6f} {ref_after_ffn[3]:.6f}")


if __name__ == "__main__":
    main()
