#!/usr/bin/env python3
"""gen_engine_tiu_data.py — real layer0 activation for M2 engine TIU-core test.

Emits qwen_engine_tiu_data.h with:
  tq_act[896]   : rms_norm(embed[105538], gamma=rms_attn layer0)  (P0 prompt 1,
                  first token — same as gen_m1_data).  The on-board test runs
                  per_row_quant on this to get x_i8 + sc_row (engine path).
"""
import os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
D = 896


def main():
    p = os.path.join(HERE, "weights_kal", "layer0_kal.bin")
    data = open(p, "rb").read()
    rms_attn = np.frombuffer(data[:D * 4], dtype=np.float32).copy()

    emb = np.fromfile(os.path.join(HERE, "weights_kal", "embed_i8.bin"),
                      dtype=np.int8).reshape(-1, D)
    esc = np.fromfile(os.path.join(HERE, "weights_kal", "embed_scales.f32"),
                      dtype=np.float32)
    x = emb[105538].astype(np.float32) * esc[105538]
    ss = np.sqrt((x.astype(np.float64) ** 2).mean() + 1e-6)
    act = (x / ss * rms_attn).astype(np.float32)

    with open(os.path.join(HERE, "qwen_engine_tiu_data.h"), "w") as f:
        f.write("/* qwen_engine_tiu_data.h — generated by gen_engine_tiu_data.py (DO NOT EDIT). */\n")
        f.write("#define TQ_D 896\n")
        f.write("static const float tq_act[896] = {")
        f.write(",".join(repr(round(float(v), 8)) for v in act))
        f.write("};\n")
    print(f"wrote qwen_engine_tiu_data.h (act[0]={act[0]:.4f}, max|act|={np.abs(act).max():.4f})")


if __name__ == "__main__":
    main()
