#!/usr/bin/env python3
"""gen_m1_data.py — extract real Qwen layer-0 blocks + activation into qwen_m1_data.h.

M1 on-board milestone data: exercises the REAL Path A data path
  INT4 K-aligned weights -> CPU per-group dequant -> per_row activation quant
  -> TIU two-pass (pass1 readback -> r_opt -> pass2).
Blocks chosen for r_opt variety:
  q_proj g=0,13,27   (N=896, r_opt ~4-5)
  down_proj g=0      (N=896, r_opt ~0-3, exercises r=0 edge)
  up_proj g=0, N[:896] (r_opt ~4-5)
Activation: rms_norm(embed[105538], gamma=rms_attn layer0)  (P0 prompt 1 first tok).
"""
import os, sys, struct
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
D, KVH, HD, F, G = 896, 2, 64, 4864, 32
DKV = KVH * HD
MATS = [("q_proj", D, D), ("k_proj", D, DKV), ("v_proj", D, DKV),
        ("o_proj", D, D), ("up_proj", D, F), ("gate_proj", D, F), ("down_proj", F, D)]

def read_layer0():
    p = os.path.join(HERE, "weights_kal", "layer0_kal.bin")
    data = open(p, "rb").read()
    off = 0
    def take(n):
        nonlocal off
        b = data[off:off + n]; off += n
        return b
    rms_attn = np.frombuffer(take(D * 4), dtype=np.float32).copy()
    mats = {}
    for name, K, N in MATS:
        nib = np.frombuffer(take((K // G) * N * 16), dtype=np.uint8).reshape(K // G, N, 16)
        gsc = np.frombuffer(take((K // G) * N * 2), dtype=np.float16).reshape(K // G, N)
        mats[name] = (nib, gsc.astype(np.float16))
    rms_ffn = np.frombuffer(take(D * 4), dtype=np.float32).copy()
    assert off == len(data)
    return rms_attn, mats, rms_ffn

def main():
    rms_attn, mats, _ = read_layer0()
    # activation: embed[105538] rms-normed with layer0 rms_attn gamma
    emb = np.fromfile(os.path.join(HERE, "weights_kal", "embed_i8.bin"), dtype=np.int8).reshape(-1, D)
    esc = np.fromfile(os.path.join(HERE, "weights_kal", "embed_scales.f32"), dtype=np.float32)
    x = emb[105538].astype(np.float32) * esc[105538]
    ss = np.sqrt((x.astype(np.float64) ** 2).mean() + 1e-6)
    act = (x / ss * rms_attn).astype(np.float32)   # rms_norm(x, gamma)

    cases = [("q0", "q_proj", 0, 896), ("q13", "q_proj", 13, 896),
             ("q27", "q_proj", 27, 896), ("dn0", "down_proj", 0, 896),
             ("up0", "up_proj", 0, 896)]

    with open(os.path.join(HERE, "qwen_m1_data.h"), "w") as f:
        f.write("/* qwen_m1_data.h — generated by gen_m1_data.py (DO NOT EDIT). */\n")
        f.write(f"#define M1_NCASE {len(cases)}\n")
        f.write("#define M1_N 896\n#define M1_G 32\n\n")
        f.write("typedef struct { const char *name; const unsigned char *nib;\n"
                "                  const unsigned short *gsc; const float *act;\n"
                "                  int koff; } M1Case;\n")
        f.write("static const float m1_act[896] = {")
        f.write(",".join(repr(round(float(v), 8)) for v in act))
        f.write("};\n\n")
        for tag, name, g, nslice in cases:
            nib, gsc = mats[name]
            nb = nib[g, :nslice, :] if name != "down_proj" else nib[g, :, :]
            gs = gsc[g, :nslice] if name != "down_proj" else gsc[g, :]
            assert nb.shape == (896, 16) and gs.shape == (896,)
            f.write(f"static const unsigned char m1_{tag}_nib[{nb.size}] = {{")
            f.write(",".join(str(int(v)) for v in nb.ravel()))
            f.write("};\n")
            f.write(f"static const unsigned short m1_{tag}_gsc[{gs.size}] = {{")
            f.write(",".join(str(int(np.float16(v).view(np.uint16))) for v in gs.ravel()))
            f.write("};\n")
        f.write("\nstatic const M1Case m1_cases[M1_NCASE] = {\n")
        for tag, name, g, nslice in cases:
            f.write(f'  {{"{tag}({name} g={g})", m1_{tag}_nib, m1_{tag}_gsc, m1_act, {g * 32}}},\n')
        f.write("};\n")
    print(f"wrote qwen_m1_data.h ({len(cases)} cases, act[0]={act[0]:.4f})")
    for tag, name, g, nslice in cases:
        nib, gsc = mats[name]
        wmax = np.abs((nib.reshape(-1, 2).view(np.int8) if False else 0))
        print(f"  {tag}: {name} g={g} N={nslice}")

if __name__ == "__main__":
    main()
